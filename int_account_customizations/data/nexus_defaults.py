"""Economic-nexus rules loaded on install.

Dollar amounts, transaction counts, measurement windows, and which sales count
follow "Economic nexus details by state". Connecticut and New York require both
tests. Delaware, Montana, New Hampshire, and Oregon have no statewide sales tax
and are omitted.

A line is classified from the order, not from the tax amount after the Out of
State position. That position means the tax is not being collected yet. The
product's own sales tax decides taxable versus exempt, the wholesale position
decides resale, and a service product (including delivery) decides services.

Edit a row in Accounting → Configuration → Sales Tax Thresholds when a state
changes its rule. Installing again does not overwrite a row that is already there.
"""


def _row(
    code, amount, transactions, trigger, period, note="",
    taxable_goods=True, exempt_goods=True,
    taxable_services=True, exempt_services=True,
    resale=True, marketplace=True, exclude_returned=False,
):
    return {
        "code": code,
        "amount": amount,
        "transactions": transactions,
        "trigger": trigger,
        "period": period,
        "note": note,
        "taxable_goods": taxable_goods,
        "exempt_goods": exempt_goods,
        "taxable_services": taxable_services,
        "exempt_services": exempt_services,
        "resale": resale,
        "marketplace": marketplace,
        "exclude_returned": exclude_returned,
    }


